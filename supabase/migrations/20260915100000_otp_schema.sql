/*
  # One-time codes: the private schema and its tables

  ## Why our own codes instead of GoTrue's links

  Every account email used to carry a GoTrue link with the token in its URL.
  Kong logs that URL, mail scanners follow it and burn the token before the
  customer does, and GoTrue offers no per-code attempt limit and no send limit
  per address or per client. Phase 1 replaces those links with six-digit codes
  that the edge functions issue, mail and verify themselves. This file holds
  the state; 20260915100100 holds the functions that are the only way in.

  ## Why a separate schema

  PostgREST serves `public` and `storage` only (deploy/docker-compose.yml,
  PGRST_DB_SCHEMAS). A table in `public` is one missing policy away from being
  readable with the anon key that ships in the browser bundle. `app_private` is
  not exposed at all, and nobody but the table owner has USAGE on it — not
  anon, not authenticated, not even service_role. The functions reach these
  tables only through SECURITY DEFINER RPCs.

  Consequence for later changes: a table or function added to this schema
  needs its own REVOKE. PostgreSQL grants EXECUTE on every new function to
  PUBLIC by a built-in default that cannot be revoked per schema; the missing
  USAGE is what actually keeps callers out, and the REVOKEs are the second
  wall.

  ## Tables

  - `otp_challenges`   one row per code that was issued. Holds an HMAC of the
                       code, never the code. At most one open row per purpose
                       and user, which is what "a new code replaces the old
                       one" is built on.
  - `otp_send_events`  one row per issue attempt that got far enough to be
                       counted, whatever its outcome. The send limits are
                       computed from it.
  - `pending_signups`  a company signup whose owner has not entered the code.
                       The only rows the unverified-signup purge may delete.
  - `platform_login_verifications`
                       a platform-admin session that has passed its code.
                       Written in Phase 1, enforced by PLATFORM in Phase 3.2.

  The limits themselves (10 minute validity, 5 attempts, 60 s cooldown, 5 per
  address per hour, 20 per client IP per hour, 12 hour platform verification)
  are declared once, as plpgsql constants, in 20260915100100.

  Purely additive: no existing object is altered.
*/

CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC, anon, authenticated, service_role;

-- ─── Challenges ─────────────────────────────────────────────────────────────

CREATE TABLE app_private.otp_challenges (
  -- Generated by the function, not by a default: the id is part of the HMAC
  -- input, so it must exist before the hash does.
  id            uuid        PRIMARY KEY,
  purpose       text        NOT NULL CHECK (purpose IN
                  ('signup_verify','password_reset','invite_activate','email_change','platform_login')),
  user_id       uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  -- The account's address when the code was issued. A later change of address
  -- does not follow the challenge; the verify path re-checks the account.
  email         text        NOT NULL CHECK (email = lower(email)),
  new_email     text        NULL     CHECK (new_email = lower(new_email)),
  -- auth.sessions.id from the caller's JWT, platform_login only. No FK: GoTrue
  -- owns that table and rewrites it on every refresh.
  session_id    uuid        NULL,
  code_hash     text        NOT NULL CHECK (code_hash ~ '^[0-9a-f]{64}$'),
  attempts      smallint    NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  created_at    timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL,
  consumed_at   timestamptz NULL,
  superseded_at timestamptz NULL,
  client_ip     inet        NULL,
  CONSTRAINT otp_new_email_iff_change  CHECK ((purpose = 'email_change')   = (new_email  IS NOT NULL)),
  CONSTRAINT otp_session_iff_platform  CHECK ((purpose = 'platform_login') = (session_id IS NOT NULL)),
  CONSTRAINT otp_expiry_after_creation CHECK (expires_at > created_at),
  CONSTRAINT otp_closed_once           CHECK (NOT (consumed_at IS NOT NULL AND superseded_at IS NOT NULL))
);

-- At most one open challenge per purpose and user. otp_issue closes the old
-- row before inserting the new one; this index is what guarantees that two
-- valid codes for the same purpose can never coexist.
CREATE UNIQUE INDEX otp_challenges_one_open ON app_private.otp_challenges (purpose, user_id)
  WHERE consumed_at IS NULL AND superseded_at IS NULL;

-- otp-verify finds the open challenge by the address the user typed.
CREATE INDEX otp_challenges_open_by_email ON app_private.otp_challenges (purpose, email)
  WHERE consumed_at IS NULL AND superseded_at IS NULL;

CREATE INDEX otp_challenges_created_at ON app_private.otp_challenges (created_at);

-- ─── Send events ────────────────────────────────────────────────────────────

CREATE TABLE app_private.otp_send_events (
  id              bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  created_at      timestamptz NOT NULL DEFAULT now(),
  purpose         text        NOT NULL CHECK (purpose IN
                    ('signup_verify','password_reset','invite_activate','email_change','platform_login')),
  recipient_email text        NOT NULL CHECK (recipient_email = lower(recipient_email)),
  client_ip       inet        NULL,
  -- No FK: an event must outlive a deleted user until the purge removes it,
  -- or deleting an account would reset its send limits.
  user_id         uuid        NULL,
  actor_user_id   uuid        NULL,   -- the admin who triggered an invite
  challenge_id    uuid        NULL,
  outcome         text        NOT NULL CHECK (outcome IN
    ('issued','send_failed','no_user','ineligible','same_email','email_taken','cooldown','email_hourly'))
);

-- Cooldown and hourly limit per address count only codes that were issued.
CREATE INDEX otp_send_events_recipient_issued ON app_private.otp_send_events (recipient_email, created_at)
  WHERE outcome = 'issued';

-- The per-IP limit counts every outcome, so it cannot be used to tell an
-- existing account from a missing one.
CREATE INDEX otp_send_events_ip ON app_private.otp_send_events (client_ip, created_at)
  WHERE client_ip IS NOT NULL;

CREATE INDEX otp_send_events_created_at ON app_private.otp_send_events (created_at);

-- ─── Pending signups ────────────────────────────────────────────────────────

-- A signup whose owner has not entered the code yet. Only rows here may ever
-- be purged: legacy unconfirmed accounts in production were never written to
-- this table, so no automatic job can reach them.
CREATE TABLE app_private.pending_signups (
  user_id       uuid        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  company_id    uuid        NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  -- Redeemed at verification, not at signup: a limited code would otherwise
  -- be used up by signups nobody ever confirms.
  discount_code text        NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);

-- ─── Platform login verifications ───────────────────────────────────────────

-- Written in Phase 1 by otp_verify; read by is_user_super_admin() through
-- app_private.platform_login_verified() from Phase 3.2 on.
CREATE TABLE app_private.platform_login_verifications (
  session_id   uuid        PRIMARY KEY,   -- auth.sessions.id from the JWT; GoTrue owns that table
  user_id      uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  challenge_id uuid        NOT NULL,
  verified_at  timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL
);

CREATE INDEX platform_login_verifications_user ON app_private.platform_login_verifications (user_id);

-- ─── Privileges ─────────────────────────────────────────────────────────────

REVOKE ALL ON ALL TABLES    IN SCHEMA app_private FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA app_private FROM PUBLIC, anon, authenticated, service_role;

-- ─── Self-check ─────────────────────────────────────────────────────────────

-- Fails the migration, and with it the release, if a role the API
-- authenticates as can reach the schema or anything in it. Default privileges
-- on the database, not this file, decide what a new table starts with.
DO $$
DECLARE
  v_role text;
  v_rel  text;
BEGIN
  FOREACH v_role IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF has_schema_privilege(v_role, 'app_private', 'USAGE') THEN
      RAISE EXCEPTION '20260915100000 self-check: % has USAGE on app_private', v_role;
    END IF;

    SELECT c.relname INTO v_rel
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'app_private'
       AND ((c.relkind = 'r' AND has_table_privilege(v_role, c.oid,
               'SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER'))
         OR (c.relkind = 'S' AND has_sequence_privilege(v_role, c.oid, 'USAGE, SELECT, UPDATE')))
     LIMIT 1;

    IF v_rel IS NOT NULL THEN
      RAISE EXCEPTION '20260915100000 self-check: % holds a privilege on app_private.%', v_role, v_rel;
    END IF;
  END LOOP;
END $$;
